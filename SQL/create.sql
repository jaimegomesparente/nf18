    id_contrepartie INT NOT NULL,
    format_fichier VARCHAR(20) NOT NULL,
    taille_mo NUMERIC(10, 2) NOT NULL,
    CONSTRAINT PK_CONTREPARTIE_NUMERIQUE PRIMARY KEY (id_contrepartie),
    CONSTRAINT FK_CONTREPARTIE_NUM_MOTHER FOREIGN KEY (id_contrepartie)
        REFERENCES CONTREPARTIE(id_contrepartie)
        ON DELETE CASCADE
        ON UPDATE CASCADE,
