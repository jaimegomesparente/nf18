    CONSTRAINT PK_PROJET_TECHNOLOGIQUE PRIMARY KEY (id_projet),
    CONSTRAINT FK_PROJET_TECH_PROJET FOREIGN KEY (id_projet)
        REFERENCES PROJET(id_projet)
        ON DELETE CASCADE
        ON UPDATE CASCADE
);

-- Table : PROJET_ARTISTIQUE (Spécialisation de PROJET)
