-- Table : ONG
CREATE TABLE ONG (
    numero_enregistrement VARCHAR(30) NOT NULL,
    nom VARCHAR(100) NOT NULL,
    pays_origine VARCHAR(60) NOT NULL,
    CONSTRAINT PK_ONG PRIMARY KEY (numero_enregistrement)
);

-- Table : SOUTIEN (Association N:M entre PROJET_SOCIAL et ONG)
CREATE TABLE SOUTIEN (
    id_projet INT NOT NULL,
    numero_enregistrement VARCHAR(30) NOT NULL,
    CONSTRAINT PK_SOUTIEN PRIMARY KEY (id_projet, numero_enregistrement),
    CONSTRAINT FK_SOUTIEN_PROJET_SOCIAL FOREIGN KEY (id_projet)
        REFERENCES PROJET_SOCIAL(id_projet)
        ON DELETE CASCADE
        ON UPDATE CASCADE,
    CONSTRAINT FK_SOUTIEN_ONG FOREIGN KEY (numero_enregistrement)
        REFERENCES ONG(numero_enregistrement)
        ON DELETE CASCADE
        ON UPDATE CASCADE
);

-- Table : MEMBRE_EQUIPE
CREATE TABLE MEMBRE_EQUIPE (
    id_membre INT GENERATED ALWAYS AS IDENTITY,
    nom VARCHAR(60) NOT NULL,
    prenom VARCHAR(60) NOT NULL,
    pays_residence VARCHAR(60) NOT NULL,
    date_naissance DATE NOT NULL,
    CONSTRAINT PK_MEMBRE_EQUIPE PRIMARY KEY (id_membre)
);

-- Table : PARTICIPATION (Classe-association entre PROJET et MEMBRE_EQUIPE)
CREATE TABLE PARTICIPATION (
    id_projet INT NOT NULL,
    id_membre INT NOT NULL,
    role VARCHAR(20) NOT NULL,
    CONSTRAINT PK_PARTICIPATION PRIMARY KEY (id_projet, id_membre),
    CONSTRAINT FK_PARTICIPATION_PROJET FOREIGN KEY (id_projet)
        REFERENCES PROJET(id_projet)
        ON DELETE CASCADE
        ON UPDATE CASCADE,
    CONSTRAINT FK_PARTICIPATION_MEMBRE FOREIGN KEY (id_membre)
        REFERENCES MEMBRE_EQUIPE(id_membre)
        ON DELETE CASCADE
        ON UPDATE CASCADE,
    CONSTRAINT CHK_PARTICIPATION_ROLE CHECK (
        role IN ('chefDeProjet', 'developpeur', 'designer', 'communityManager')
    )
);

-- Table : UTILISATEUR
