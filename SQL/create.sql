-- Table : CONTREPARTIE_PHYSIQUE (Spécialisation de CONTREPARTIE)
CREATE TABLE CONTREPARTIE_PHYSIQUE (
    id_contrepartie INT NOT NULL,
    poids_estime NUMERIC(8, 2) NOT NULL,
    frais_livraison NUMERIC(8, 2) NOT NULL,
    nom_transporteur VARCHAR(60) NOT NULL,
    CONSTRAINT PK_CONTREPARTIE_PHYSIQUE PRIMARY KEY (id_contrepartie),
    CONSTRAINT FK_CONTREPARTIE_PHYS_MOTHER FOREIGN KEY (id_contrepartie)
        REFERENCES CONTREPARTIE(id_contrepartie)
        ON DELETE CASCADE
        ON UPDATE CASCADE,
    CONSTRAINT FK_CONTREPARTIE_PHYS_TRANSPORTEUR FOREIGN KEY (nom_transporteur)
        REFERENCES TRANSPORTEUR(nom)
        ON DELETE RESTRICT
        ON UPDATE CASCADE,
    CONSTRAINT CHK_CONTREPARTIE_PHYS_POIDS CHECK (poids_estime > 0),
    CONSTRAINT CHK_CONTREPARTIE_PHYS_FRAIS CHECK (frais_livraison >= 0)
);

-- Table : CONTRIBUTION
CREATE TABLE CONTRIBUTION (
    pseudo VARCHAR(30) NOT NULL,
    id_projet INT NOT NULL,
    date_heure TIMESTAMP NOT NULL,
    montant NUMERIC(12, 2) NOT NULL,
    id_contrepartie INT,
    CONSTRAINT PK_CONTRIBUTION PRIMARY KEY (pseudo, id_projet, date_heure),
    CONSTRAINT FK_CONTRIBUTION_UTILISATEUR FOREIGN KEY (pseudo)
        REFERENCES UTILISATEUR(pseudo)
        ON DELETE CASCADE
        ON UPDATE CASCADE,
    CONSTRAINT FK_CONTRIBUTION_PROJET FOREIGN KEY (id_projet)
        REFERENCES PROJET(id_projet)
        ON DELETE CASCADE
        ON UPDATE CASCADE,
    CONSTRAINT FK_CONTRIBUTION_CONTREPARTIE FOREIGN KEY (id_contrepartie)
        REFERENCES CONTREPARTIE(id_contrepartie)
        ON DELETE SET NULL
        ON UPDATE CASCADE,
    CONSTRAINT CHK_CONTRIBUTION_MONTANT CHECK (montant > 0)
);

-- Table : AVIS
CREATE TABLE AVIS (
    pseudo VARCHAR(30) NOT NULL,
    id_projet INT NOT NULL,
    note INT NOT NULL,
    avis_textuel TEXT NOT NULL,
    date_avis DATE NOT NULL,
    CONSTRAINT PK_AVIS PRIMARY KEY (pseudo, id_projet),
    CONSTRAINT FK_AVIS_UTILISATEUR FOREIGN KEY (pseudo)
        REFERENCES UTILISATEUR(pseudo)
        ON DELETE CASCADE
        ON UPDATE CASCADE,
    CONSTRAINT FK_AVIS_PROJET FOREIGN KEY (id_projet)
        REFERENCES PROJET(id_projet)
        ON DELETE CASCADE
        ON UPDATE CASCADE,
    CONSTRAINT CHK_AVIS_NOTE CHECK (note BETWEEN 1 AND 5)
);