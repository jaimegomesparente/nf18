-- Table : INCUBATEUR

CREATE TABLE INCUBATEUR (
    id_incubateur INT GENERATED ALWAYS AS IDENTITY, -- Garantie l'unicité en incrementant automatiquement l'id par rapport à ce qui est déjà dans la BD
    nom VARCHAR(100) NOT NULL,
    annee_creation INT NOT NULL,
    budget_accompagnement NUMERIC(12, 2) NOT NULL,
    CONSTRAINT PK_INCUBATEUR PRIMARY KEY (id_incubateur),
    CONSTRAINT CHK_INCUBATEUR_ANNEE CHECK (annee_creation >= 1800),
    CONSTRAINT CHK_INCUBATEUR_BUDGET CHECK (budget_accompagnement >= 0)
);

-- Table : PROJET (Classe mère abstraite)
CREATE TABLE PROJET (
    id_projet INT GENERATED ALWAYS AS IDENTITY,
    titre VARCHAR(150) NOT NULL,
    description TEXT NOT NULL,
    objectif_financier NUMERIC(12, 2) NOT NULL,
    date_lancement DATE NOT NULL,
    id_incubateur INT,
    CONSTRAINT PK_PROJET PRIMARY KEY (id_projet),
    CONSTRAINT FK_PROJET_INCUBATEUR FOREIGN KEY (id_incubateur)
        REFERENCES INCUBATEUR(id_incubateur)
        ON DELETE SET NULL
        ON UPDATE CASCADE,
    CONSTRAINT CHK_PROJET_OBJECTIF CHECK (objectif_financier > 0)
);

-- Table : PROJET_TECHNOLOGIQUE (Spécialisation de PROJET)
CREATE TABLE PROJET_TECHNOLOGIQUE (
