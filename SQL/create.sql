    CONSTRAINT PK_CONTREPARTIE PRIMARY KEY (id_contrepartie),
    CONSTRAINT FK_CONTREPARTIE_PROJET FOREIGN KEY (id_projet)
        REFERENCES PROJET(id_projet)
        ON DELETE CASCADE
        ON UPDATE CASCADE
);

-- Table : CONTREPARTIE_NUMERIQUE (Spécialisation de CONTREPARTIE)
